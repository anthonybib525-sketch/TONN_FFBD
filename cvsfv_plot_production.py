# Block 6 - Fourier feature density network
# ============================================================
class FourierFeatureMap(nn.Module):
    def __init__(self, in_dim: int, num_fourier_features: int, sigma: float, seed: int = 0):
        super().__init__()

        gen = torch.Generator(device="cpu")
        gen.manual_seed(seed)

        B = torch.randn((num_fourier_features, in_dim), generator=gen) * sigma
        self.register_buffer("B", B)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        xb = 2.0 * math.pi * (x @ self.B.T)
        return torch.cat([torch.cos(xb), torch.sin(xb)], dim=1)


class PaperStyleFourierDensityNet(nn.Module):
    def __init__(self, cfg: Config):
        super().__init__()

        self.fourier = FourierFeatureMap(
            in_dim=2,
            num_fourier_features=cfg.num_fourier_features,
            sigma=cfg.fourier_sigma,
            seed=cfg.fourier_seed,
        )

        input_dim = 2 * cfg.num_fourier_features
        in_dim = input_dim

        self.hidden_linears = nn.ModuleList()

        for _ in range(cfg.num_hidden_layers):
            linear = nn.Linear(in_dim, cfg.hidden_width)
            self.hidden_linears.append(linear)
            in_dim = cfg.hidden_width

        self.out = nn.Linear(in_dim, 1)

        # Hidden-layer activation
        self.activation = nn.LeakyReLU(negative_slope=0.01)

        self.reset_parameters(cfg.volfrac)

    def reset_parameters(self, volfrac: float):
        for linear in self.hidden_linears:
            nn.init.orthogonal_(linear.weight)
            nn.init.zeros_(linear.bias)

        nn.init.normal_(self.out.weight, mean=0.0, std=1e-4)
        nn.init.constant_(self.out.bias, safe_logit(volfrac))

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        z = self.fourier(x)

        h = z
        for linear in self.hidden_linears:
            h = self.activation(linear(h))

        logits = self.out(h)

        return torch.sigmoid(logits).squeeze(1)


