def main():
    base_cfg = Config(
        device="auto",
        out_dir="/content/tounn_fourier_feature_sensitivity_outputs",
    )

    results = []

    for d in base_cfg.fourier_feature_list:
        print("\n\n")
        print("#" * 100)
        print(f"Starting Fourier-feature sensitivity case: d = {d}")
        print("#" * 100)

        cfg = replace(base_cfg, num_fourier_features=d)

        clear_memory()

        model, history, problem_data, device = train(cfg)

        result_row = save_results_for_single_run(
            model=model,
            history=history,
            cfg=cfg,
            problem_data=problem_data,
            device=device,
        )

        results.append(result_row)

        del model
        del history
        del problem_data

        clear_memory()

    save_sensitivity_summary(results, base_cfg)
    plot_sensitivity_compliance_summary(results, base_cfg)

    print("\nCompleted Fourier-feature-number sensitivity study.")
    print("Summary of final compliance values:")
    for row in results:
        print(
            f"d={row['num_fourier_features']:4d} | "
            f"C={row['final_compliance']:12.5f} | "
            f"VF={row['final_volfrac']:.5f} | "
            f"epoch={row['final_epoch']}"
        )


if __name__ == "__main__":
    main()