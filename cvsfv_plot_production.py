# Block 7 - High-resolution sampling
# ============================================================
def sample_highres_density(model, cfg, device):
    s = cfg.samples_per_element

    nx_hr = cfg.nelx * s
    ny_hr = cfg.nely * s

    dx_hr = cfg.lx / nx_hr
    dy_hr = cfg.ly / ny_hr

    xs = (np.arange(nx_hr) + 0.5) * dx_hr
    ys = (np.arange(ny_hr) + 0.5) * dy_hr

    XX, YY = np.meshgrid(xs, ys)
    pts = np.column_stack([XX.ravel(), YY.ravel()])

    with torch.no_grad():
        model.eval()
        pts_t = torch.tensor(pts, dtype=cfg.dtype, device=device)
        rho_hr = model(pts_t).detach().cpu().numpy().reshape(ny_hr, nx_hr)

    return rho_hr


