# Fourier feature map and neural density model
# ============================================================

class BoundedDiskFourierFeatureMap(nn.Module):
    def __init__(self, in_dim: int, num_fourier_features: int, fmax: float, seed: int = 0):
        super().__init__()
        if in_dim != 2:
            raise ValueError("This Fourier map assumes 2D coordinates.")
        if fmax <= 0.0:
            raise ValueError("fmax must be positive.")

        gen = torch.Generator(device="cpu")
        gen.manual_seed(seed)

        theta = 2.0 * math.pi * torch.rand(num_fourier_features, generator=gen)
        r = fmax * torch.rand(num_fourier_features, generator=gen)
        bx = r * torch.cos(theta)
        by = r * torch.sin(theta)
        B = torch.stack([bx, by], dim=1)

        self.fmax = fmax
        self.register_buffer("B", B)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        xb = 2.0 * math.pi * (x @ self.B.T)
        return torch.cat([torch.cos(xb), torch.sin(xb)], dim=1)


class FourierDensityNet(nn.Module):
    def __init__(self, cfg: Config):
        super().__init__()
        self.fourier = BoundedDiskFourierFeatureMap(
            in_dim=2,
            num_fourier_features=cfg.num_fourier_features,
            fmax=cfg.fmax,
            seed=cfg.fourier_seed,
        )

        in_dim = 2 * cfg.num_fourier_features
        self.hidden_linears = nn.ModuleList()
        for _ in range(cfg.num_hidden_layers):
            layer = nn.Linear(in_dim, cfg.hidden_width)
            self.hidden_linears.append(layer)
            in_dim = cfg.hidden_width

        self.out = nn.Linear(in_dim, 1)
        self.activation = nn.LeakyReLU(negative_slope=0.01)
        self.reset_parameters(cfg.volfrac)

    def reset_parameters(self, volfrac: float):
        for layer in self.hidden_linears:
            nn.init.orthogonal_(layer.weight)
            nn.init.zeros_(layer.bias)
        nn.init.normal_(self.out.weight, mean=0.0, std=1e-4)
        nn.init.constant_(self.out.bias, safe_logit(volfrac))

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        z = self.fourier(x)
        h = z
        for layer in self.hidden_linears:
            h = self.activation(layer(h))
        logits = self.out(h)
        return torch.sigmoid(logits).squeeze(1)


