# FEA black box and training
# ============================================================

def fea_black_box(rho_torch: torch.Tensor, problem_data: Dict[str, Any], cfg: Config) -> Tuple[np.ndarray, float]:
    rho = rho_torch.detach().cpu().numpy().astype(float)
    rho = np.clip(rho, 1e-9, 1.0)

    E_e = cfg.Emin + (rho ** cfg.penal) * (cfg.E0 - cfg.Emin)
    sK = np.outer(E_e, problem_data["KE"].ravel()).ravel()

    K = sp.coo_matrix(
        (sK, (problem_data["iK"], problem_data["jK"])),
        shape=(problem_data["ndof"], problem_data["ndof"]),
    ).tocsc()
    K = 0.5 * (K + K.T)

    U = np.zeros(problem_data["ndof"], dtype=float)
    free = problem_data["free"]
    U[free] = spla.spsolve(K[free, :][:, free], problem_data["F"][free])

    Ue = U[problem_data["edofMat"]]
    Je0 = np.einsum("ij,ij->i", Ue @ problem_data["KE"], Ue)
    compliance = float(np.sum(E_e * Je0))
    return Je0, compliance


def compute_windowed_compliance_improvement(compliance_history: List[float], window: int) -> float:
    if len(compliance_history) < 2 * window:
        return np.inf
    older = np.mean(compliance_history[-2 * window:-window])
    recent = np.mean(compliance_history[-window:])
    return abs(recent - older) / max(abs(older), 1e-12)


def get_final_density(model: nn.Module, cfg: Config, problem_data: Dict[str, Any], device: torch.device) -> np.ndarray:
    coords = torch.tensor(problem_data["centers"], dtype=cfg.dtype, device=device)
    with torch.no_grad():
        model.eval()
        rho = model(coords).detach().cpu().numpy().reshape(cfg.nely, cfg.nelx)
    return rho


def train_one_case(cfg: Config) -> Tuple[nn.Module, Dict[str, List[float]], Dict[str, Any], torch.device]:
    torch.manual_seed(cfg.fourier_seed)
    np.random.seed(cfg.fourier_seed)

    device = resolve_device(cfg.device)
    problem_data = build_problem_data(cfg)

    coords = torch.tensor(problem_data["centers"], dtype=cfg.dtype, device=device)
    elem_areas = torch.tensor(problem_data["elem_areas"], dtype=cfg.dtype, device=device)

    V_total = float(problem_data["elem_areas"].sum())
    V_star_abs = cfg.volfrac * V_total

    model = FourierDensityNet(cfg).to(device)
    optimizer = torch.optim.Adam(model.parameters(), lr=cfg.lr)

    alm_lambda = float(cfg.alm_lambda0)
    alm_mu = float(cfg.alm_mu0)
    previous_rho = None
    patience_counter = 0
    J0 = None

    history: Dict[str, List[float]] = {
        "epoch": [],
        "compliance": [],
        "volfrac": [],
        "loss": [],
        "rho_change_max": [],
        "volfrac_residual": [],
        "compliance_rel_improve": [],
        "alm_lambda": [],
        "alm_mu": [],
    }

    print("\n" + "=" * 78)
    print(f"TONN-FFBD run | case = {cfg.problem_name} | VF = {cfg.volfrac}")
    print(f"Mesh                    : {cfg.nelx} x {cfg.nely}")
    print(f"Element size            : {cfg.elem_size_x:g} in x {cfg.elem_size_y:g} in")
    print(f"Physical domain         : {cfg.lx:g} in x {cfg.ly:g} in")
    print(f"Target min length       : {cfg.target_min_length:g} in")
    print(f"fmax                    : {cfg.fmax:g} cycles/in")
    print(f"Min Fourier wavelength  : {cfg.min_fourier_wavelength:g} in")
    print(f"Fourier features        : {cfg.num_fourier_features}")
    print("=" * 78)

    for epoch in range(cfg.max_epochs):
        model.train()
        optimizer.zero_grad()

        rho = model(coords).clamp(1e-6, 1.0 - 1e-6)
        Je0_np, compliance = fea_black_box(rho, problem_data, cfg)
        Je0 = torch.tensor(Je0_np, dtype=cfg.dtype, device=device)

        V_abs = torch.sum(rho * elem_areas)
        volfrac_current = V_abs / V_total
        g_v = (V_abs / V_star_abs) - 1.0
        volfrac_residual = volfrac_current / cfg.volfrac - 1.0

        if epoch == 0:
            J0 = max(float(compliance), 1e-12)

        loss = (compliance / J0) + alm_lambda * g_v + 0.5 * alm_mu * (g_v ** 2)

        dJ_drho = (
            -cfg.penal
            * (cfg.E0 - cfg.Emin)
            * torch.pow(rho.detach(), cfg.penal - 1.0)
            * Je0
            / J0
        )
        dg_drho = elem_areas / V_star_abs
        dL_drho = dJ_drho + (alm_lambda + alm_mu * g_v.detach()) * dg_drho

        rho.backward(dL_drho)
        optimizer.step()

        if (epoch + 1) % cfg.alm_update_every == 0:
            g_scalar = float(g_v.detach().cpu())
            alm_lambda = alm_lambda + alm_mu * g_scalar
            alm_mu = min(cfg.alm_mu_max, alm_mu * cfg.alm_mu_scale)

        rho_cpu = rho.detach().cpu().numpy()
        if previous_rho is None:
            rho_change_max = np.inf
        else:
            rho_change_max = float(np.max(np.abs(rho_cpu - previous_rho)))
        previous_rho = rho_cpu.copy()

        history["epoch"].append(epoch)
        history["compliance"].append(float(compliance))
        history["volfrac"].append(float(volfrac_current.detach().cpu()))
        history["loss"].append(float(loss.detach().cpu()))
        history["rho_change_max"].append(rho_change_max)
        history["volfrac_residual"].append(float(volfrac_residual.detach().cpu()))
        history["alm_lambda"].append(float(alm_lambda))
        history["alm_mu"].append(float(alm_mu))

        compliance_rel_improve = compute_windowed_compliance_improvement(
            history["compliance"], cfg.compliance_window
        )
        history["compliance_rel_improve"].append(compliance_rel_improve)

        enough_epochs = epoch >= cfg.min_epochs_before_stop
        volume_ok = abs(float(volfrac_residual.detach().cpu())) < cfg.volfrac_residual_tol
        rho_ok = rho_change_max < cfg.rho_change_max_tol
        compliance_ok = compliance_rel_improve < cfg.compliance_rel_improve_tol

        if enough_epochs and volume_ok or rho_ok and compliance_ok:
            patience_counter += 1
        else:
            patience_counter = 0

        if epoch % cfg.print_every == 0 or epoch == cfg.max_epochs - 1:
            improve_str = f"{compliance_rel_improve:9.3e}" if np.isfinite(compliance_rel_improve) else "      inf"
            print(
                f"iter={epoch:5d} | "
                f"loss={float(loss.detach().cpu()):11.5f} | "
                f"C={float(compliance):12.5f} | "
                f"VF={float(volfrac_current.detach().cpu()):8.5f} | "
                f"gVF={float(volfrac_residual.detach().cpu()):+9.5f} | "
                f"lam={alm_lambda:+10.3e} | "
                f"mu={alm_mu:10.3e} | "
                f"max|dRho|={rho_change_max:9.3e} | "
                f"rel dC={improve_str} | "
                f"pat={patience_counter}/{cfg.patience}"
            )

        if patience_counter >= cfg.patience:
            print(f"Converged at iteration {epoch}.")
            break

    return model, history, problem_data, device


