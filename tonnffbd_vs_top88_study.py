def case_display_name(problem_name: str) -> str:
    if problem_name == "MBB":
        return "MBB"
    if problem_name == "Tip_loaded_cantilever":
        return "Tip-loaded Cantilever"
    return problem_name


def run_batch_study():
    problem_list = ["MBB", "Tip_loaded_cantilever"]
    volfrac_list = [0.2, 0.4, 0.6]

    base_cfg = Config()
    out_dir = Path(base_cfg.out_dir)
    if base_cfg.save_figures:
        out_dir.mkdir(parents=True, exist_ok=True)

    all_results: Dict[str, List[Dict[str, Any]]] = {p: [] for p in problem_list}

    for problem_name in problem_list:
        for vf in volfrac_list:
            cfg = Config(problem_name=problem_name, volfrac=vf)
            model, history, problem_data, device = train_one_case(cfg)
            rho = get_final_density(model, cfg, problem_data, device)

            final_compliance = history["compliance"][-1]
            final_vf = history["volfrac"][-1]
            final_epoch = history["epoch"][-1]

            all_results[problem_name].append({
                "cfg": cfg,
                "rho": rho,
                "history": history,
                "compliance": final_compliance,
                "volfrac_final": final_vf,
                "epoch": final_epoch,
            })

            del model
            if torch.cuda.is_available():
                torch.cuda.empty_cache()
            gc.collect()

    for problem_name in problem_list:
        display_name = case_display_name(problem_name)
        fig, axes = plt.subplots(3, 1, figsize=(9, 8), constrained_layout=True)

        for ax, result in zip(axes, all_results[problem_name]):
            cfg = result["cfg"]
            rho = result["rho"]
            ax.imshow(
                rho,
                cmap="gray_r",
                origin="lower",
                vmin=0.0,
                vmax=1.0,
                extent=[0, cfg.lx, 0, cfg.ly],
                aspect="equal",
                interpolation="nearest",
            )
            ax.set_axis_off()

            num_iter = result["epoch"] + 1

            ax.set_title(
                f"{display_name} | VF = {cfg.volfrac:.1f} | "
                f"C = {result['compliance']:.6g} | "
                f"VF_final = {result['volfrac_final']:.4f} | "
                f"Iterations = {num_iter}",
                fontsize=11,
                fontweight="normal",
            )
        fig.suptitle(
            f"TONN-FFBD Benchmark: {display_name} | "
            f"{base_cfg.nelx}x{base_cfg.nely} | Lmin = {base_cfg.target_min_length:g} in",
            fontsize=13,
            fontweight="bold",
        )

        if base_cfg.save_figures:
            safe_name = problem_name.lower()
            fig.savefig(out_dir / f"TONN_FFBD_{safe_name}_VF_study.png", dpi=300, bbox_inches="tight")

        plt.show()
        plt.close(fig)

    print("\n================ FINAL SUMMARY ================")
    for problem_name in problem_list:
        for result in all_results[problem_name]:
            cfg = result["cfg"]
            print(
                f"TONN-FFBD | {problem_name:24s} | "
                f"VF target = {cfg.volfrac:.2f} | "
                f"VF final = {result['volfrac_final']:.6f} | "
                f"C = {result['compliance']:.8g} | "
                f"epoch = {result['epoch']}"
            )
    print("================================================")

    if base_cfg.save_figures:
        print(f"\nSaved figures to:\n{out_dir.resolve()}")

    return all_results


if __name__ == "__main__":
    all_results = run_batch_study()