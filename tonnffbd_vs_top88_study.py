@dataclass
class Config:
    # Mesh and physical domain
    nelx: int = 90
    nely: int = 30
    elem_size_x: float = 0.1
    elem_size_y: float = 0.1

    # Study variables
    volfrac: float = 0.4
    problem_name: str = "MBB"

    # Material and SIMP
    E0: float = 1.0
    Emin: float = 1e-9
    nu: float = 0.3
    plane_stress: bool = True
    penal: float = 3.0

    # Bounded-disk Fourier features
    num_fourier_features: int = 512
    fourier_seed: int = 0
    target_min_length: float = 0.3

    # This keeps the same convention as your latest TONN-FFBD code.
    # Current rule: fmax = 1 / (6 * target_min_length).
    use_current_fmax_rule: bool = True

    # Neural network
    num_hidden_layers: int = 4
    hidden_width: int = 256

    # Optimizer
    lr: float = 1e-3
    max_epochs: int = 1000

    # Equality ALM for VF = target VF
    alm_lambda0: float = 0.0
    alm_mu0: float = 5
    alm_update_every: int = 50
    alm_mu_scale: float = 1.2
    alm_mu_max: float = 50

    # Stopping rule
    rho_change_max_tol: float = 0.05
    volfrac_residual_tol: float = 0.001
    compliance_rel_improve_tol: float = 1e-4
    compliance_window: int = 10
    patience: int = 20
    min_epochs_before_stop: int = 100

    # Misc
    print_every: int = 50
    save_figures: bool = True
    out_dir: str = "./tonn_ffbd_batch_outputs"
    device: str = "auto"
    dtype: torch.dtype = torch.float32

    @property
    def lx(self) -> float:
        return self.nelx * self.elem_size_x

    @property
    def ly(self) -> float:
        return self.nely * self.elem_size_y

    @property
    def fmax(self) -> float:
        if self.target_min_length <= 0.0:
            raise ValueError("target_min_length must be positive.")
        if self.use_current_fmax_rule:
            return 1.0 / (5.0 * self.target_min_length)
        return 1.0 / self.target_min_length

    @property
    def min_fourier_wavelength(self) -> float:
        return 1.0 / self.fmax


def resolve_device(device_string: str) -> torch.device:
    if device_string == "auto":
        return torch.device("cuda" if torch.cuda.is_available() else "cpu")
    if device_string == "cuda" and not torch.cuda.is_available():
        print("Requested CUDA, but CUDA is unavailable. Falling back to CPU.")
        return torch.device("cpu")
    return torch.device(device_string)


def safe_logit(p: float, eps: float = 1e-6) -> float:
    p = float(np.clip(p, eps, 1.0 - eps))
    return math.log(p / (1.0 - p))


