def remove_small_components(mask: np.ndarray, min_area_pixels: int) -> np.ndarray:
    if min_area_pixels <= 0:
        return mask.astype(bool)

    labels, nlab = ndi.label(mask)

    if nlab == 0:
        return mask.astype(bool)

    counts = np.bincount(labels.ravel())
    keep = np.zeros_like(counts, dtype=bool)
    keep[counts >= min_area_pixels] = True
    keep[0] = False

    return keep[labels]


def compute_skeleton(mask: np.ndarray) -> np.ndarray:
    mask = mask.astype(bool)

    if SKIMAGE_AVAILABLE:
        return skeletonize(mask)

    dist = ndi.distance_transform_edt(mask)
    local_max = dist == ndi.maximum_filter(dist, size=3)

    return local_max & mask


def analyze_region_thickness(
    region_mask: np.ndarray,
    dx: float,
    dy: float,
    target_min_length: float,
    min_component_area_pixels: int = 20,
) -> Dict[str, Any]:

    region_mask = region_mask.astype(bool)
    region_mask = remove_small_components(region_mask, min_component_area_pixels)

    if np.sum(region_mask) == 0:
        return {
            "valid": False,
            "message": "Region mask is empty.",
        }

    dist = ndi.distance_transform_edt(region_mask, sampling=(dy, dx))
    skel = compute_skeleton(region_mask)
    valid_skel = skel & (dist > 0.0)

    if np.sum(valid_skel) == 0:
        return {
            "valid": False,
            "message": "Skeleton is empty.",
            "distance": dist,
            "skeleton": skel,
        }

    thickness = 2.0 * dist

    skel_values = thickness[valid_skel]
    candidate_indices = np.flatnonzero(valid_skel)

    min_local_index = int(np.argmin(skel_values))
    min_flat_index = int(candidate_indices[min_local_index])
    row, col = np.unravel_index(min_flat_index, region_mask.shape)

    min_thickness = float(thickness[row, col])
    local_radius = float(dist[row, col])

    violation_mask = valid_skel & (thickness < target_min_length)
    violation_fraction = float(np.sum(violation_mask) / max(np.sum(valid_skel), 1))

    return {
        "valid": True,
        "distance": dist,
        "thickness": thickness,
        "skeleton": skel,
        "valid_skeleton": valid_skel,
        "violation_mask": violation_mask,
        "min_thickness": min_thickness,
        "critical_row": int(row),
        "critical_col": int(col),
        "critical_radius": local_radius,
        "violation_fraction": violation_fraction,
        "num_skeleton_pixels": int(np.sum(valid_skel)),
    }


def analyze_lengthscale(rho_hr: np.ndarray, cfg: Config) -> Dict[str, Any]:
    ny_hr, nx_hr = rho_hr.shape

    dx_hr = cfg.lx / nx_hr
    dy_hr = cfg.ly / ny_hr

    solid_mask = rho_hr >= cfg.density_threshold
    void_mask = ~solid_mask

    solid_result = analyze_region_thickness(
        region_mask=solid_mask,
        dx=dx_hr,
        dy=dy_hr,
        target_min_length=cfg.target_min_length,
        min_component_area_pixels=cfg.min_component_area_pixels,
    )

    if cfg.compute_void_thickness:
        void_result = analyze_region_thickness(
            region_mask=void_mask,
            dx=dx_hr,
            dy=dy_hr,
            target_min_length=cfg.target_min_length,
            min_component_area_pixels=cfg.min_component_area_pixels,
        )
    else:
        void_result = {
            "valid": False,
            "message": "Void thickness not requested.",
        }

    return {
        "dx_hr": dx_hr,
        "dy_hr": dy_hr,
        "solid_mask": solid_mask,
        "void_mask": void_mask,
        "solid": solid_result,
        "void": void_result,
    }


def pixel_to_physical(row: int, col: int, cfg: Config, rho_hr: np.ndarray):
    ny_hr, nx_hr = rho_hr.shape
    dx_hr = cfg.lx / nx_hr
    dy_hr = cfg.ly / ny_hr

    x = (col + 0.5) * dx_hr
    y = (row + 0.5) * dy_hr

    return x, y


