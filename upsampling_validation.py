def evaluate_model_on_cfg(model: nn.Module, train_cfg: Config, eval_cfg: Config, device: torch.device):
    """
    Evaluate a trained coordinate NN on the centroids of a different FE mesh,
    then compute the compliance of that density field using the target mesh.

    The NN remains the same. Only the sampling coordinates and FE mesh change.
    """
    eval_data = build_problem_data(eval_cfg)
    coords_eval = torch.tensor(eval_data["centers"], dtype=train_cfg.dtype, device=device)

    model.eval()
    with torch.no_grad():
        rho_eval = model(coords_eval).clamp(1e-6, 1.0 - 1e-6)

    _, compliance_eval = fea_black_box(rho_eval, eval_data, eval_cfg)

    rho_grid = rho_eval.detach().cpu().numpy().reshape(eval_cfg.nely, eval_cfg.nelx)
    vf_eval = float(np.mean(rho_grid))

    return {
        "rho_grid": rho_grid,
        "compliance": float(compliance_eval),
        "volfrac": vf_eval,
        "problem_data": eval_data,
    }


def evaluate_density_grid_on_cfg(rho_grid: np.ndarray, eval_cfg: Config):
    """
    Compute compliance directly from a supplied density grid on eval_cfg.
    This is useful for optional thresholded/binary checks.
    """
    eval_data = build_problem_data(eval_cfg)
    rho_flat = torch.tensor(rho_grid.ravel(), dtype=eval_cfg.dtype)
    _, compliance = fea_black_box(rho_flat, eval_data, eval_cfg)
    return float(compliance), float(np.mean(rho_grid))


def threshold_to_target_vf(rho_grid: np.ndarray, volfrac: float):
    """
    Binarize while approximately preserving the requested volume fraction.
    The highest-density elements are kept as solid.
    """
    flat = rho_grid.ravel()
    nele = flat.size
    keep = int(round(volfrac * nele))
    keep = max(1, min(nele, keep))

    order = np.argsort(flat)[::-1]
    binary = np.zeros_like(flat)
    binary[order[:keep]] = 1.0
    return binary.reshape(rho_grid.shape)


