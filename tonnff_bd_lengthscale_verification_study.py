def sample_highres_density(model, cfg, device):
    s = cfg.samples_per_element

    nx_hr = cfg.nelx * s
    ny_hr = cfg.nely * s

    dx_hr = cfg.lx / nx_hr
    dy_hr = cfg.ly / ny_hr

    xs = (np.arange(nx_hr) + 0.5) * dx_hr
    ys = (np.arange(ny_hr) + 0.5) * dy_hr

    XX, YY = np.meshgrid(xs, ys)
    pts = np.column_stack([XX.ravel(), YY.ravel()])

    rho_chunks = []

    with torch.no_grad():
        model.eval()

        for i in range(0, pts.shape[0], cfg.highres_batch_size):
            batch = pts[i:i + cfg.highres_batch_size]
            pts_t = torch.tensor(batch, dtype=cfg.dtype, device=device)
            rho_batch = model(pts_t).detach().cpu().numpy()
            rho_chunks.append(rho_batch)

    rho_hr = np.concatenate(rho_chunks).reshape(ny_hr, nx_hr)

    return rho_hr


def get_final_density(model, cfg, problem_data, device):
    coords = torch.tensor(problem_data["centers"], dtype=cfg.dtype, device=device)

    with torch.no_grad():
        model.eval()
        rho = model(coords).detach().cpu().numpy().reshape(cfg.nely, cfg.nelx)

    return rho


