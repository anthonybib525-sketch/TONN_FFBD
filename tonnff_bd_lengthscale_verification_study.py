        f.write(f"fmax_factor_x                : {cfg.fmax_factor}\n")
        f.write(f"target_min_length            : {cfg.target_min_length}\n")
        f.write(f"fmax                         : {cfg.fmax}\n")
        f.write(f"min_fourier_wavelength       : {cfg.min_fourier_wavelength}\n")
        f.write(f"half_wavelength_estimate     : {cfg.half_wavelength_estimate}\n")
        f.write(f"final_compliance             : {final_compliance}\n")
        f.write(f"final_volfrac                : {final_volfrac}\n")
        f.write(f"final_epoch                  : {final_epoch}\n")
        f.write(f"solid_min_thickness          : {solid_min_thickness}\n")
        f.write(f"solid_violation_fraction     : {solid_violation_fraction}\n")
        f.write(f"void_min_thickness           : {void_min_thickness}\n")
        f.write(f"void_violation_fraction      : {void_violation_fraction}\n")
        f.write(f"density_threshold            : {cfg.density_threshold}\n")

