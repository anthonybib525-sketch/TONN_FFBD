def plot_metric_vs_factor(
    results: List[Dict[str, Any]],
    metric_key: str,
    ylabel: str,
    title: str,
    out_path: Path,
):
    fig, ax = plt.subplots(figsize=(8, 5))

    problems = sorted(set(r["problem_name"] for r in results))

    for problem in problems:
        rows = [r for r in results if r["problem_name"] == problem]
        rows = sorted(rows, key=lambda r: r["fmax_factor_x"])

        xs = [r["fmax_factor_x"] for r in rows]
        ys = [r[metric_key] for r in rows]

        ax.plot(xs, ys, marker="o", label=problem)

    ax.set_xlabel(r"factor $x$ in $f_{\max}=1/(x\ell_{\min})$")
    ax.set_ylabel(ylabel)
    ax.set_title(title)
    ax.grid(True, alpha=0.3)
    ax.legend()

    plt.tight_layout()
    fig.savefig(out_path, dpi=300, bbox_inches="tight")
    plt.close(fig)


