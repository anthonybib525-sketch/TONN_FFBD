def train(cfg: Config):
    device = resolve_device(cfg.device)
    problem_data = build_problem_data(cfg)

    coords = torch.tensor(problem_data["centers"], dtype=cfg.dtype, device=device)
    elem_areas = torch.tensor(problem_data["elem_areas"], dtype=cfg.dtype, device=device)

    V_total = float(problem_data["elem_areas"].sum())
    V_star_abs = cfg.volfrac * V_total

    model = FourierDensityNet(cfg).to(device)
    optimizer = torch.optim.Adam(model.parameters(), lr=cfg.lr)

    previous_rho = None
    patience_counter = 0

    alm_lambda = float(cfg.alm_lambda0)
    alm_mu = float(cfg.alm_mu0)
    prev_g_plus_for_mu = None

    J0 = None

    history = {
        "epoch": [],
        "compliance": [],
        "volfrac": [],
        "loss": [],
        "rho_change_max": [],
        "volfrac_residual": [],
        "compliance_rel_improve": [],
        "patience_counter": [],
        "alm_lambda": [],
        "alm_mu": [],
        "g_plus": [],
    }

    print("=" * 92)
    print(f"Case: problem={cfg.problem_name} | x={cfg.fmax_factor} | fmax={cfg.fmax:.6g}")
    print(f"Target Lmin={cfg.target_min_length:.6g} in | min Fourier wavelength={cfg.min_fourier_wavelength:.6g} in")
    print(f"Mesh={cfg.nelx}x{cfg.nely} | domain={cfg.lx:g}x{cfg.ly:g} in | device={device}")
    print("=" * 92)

    for epoch in range(cfg.max_epochs):
        model.train()
        optimizer.zero_grad()

        rho = model(coords).clamp(1e-6, 1.0 - 1e-6)

        Je0_np, compliance = fea_black_box(rho, problem_data, cfg)
        Je0 = torch.tensor(Je0_np, dtype=cfg.dtype, device=device)

        V_abs = torch.sum(rho * elem_areas)
        volfrac_current = V_abs / V_total
        volfrac_residual = volfrac_current / cfg.volfrac - 1.0

        g_v = (V_abs / V_star_abs) - 1.0
        g_plus = torch.clamp(g_v, min=0.0)

        if epoch == 0:
            J0 = max(float(compliance), 1e-12)

        loss = (compliance / J0) + alm_lambda * g_plus + 0.5 * alm_mu * (g_plus ** 2)

        dJ_drho = (
            -cfg.penal
            * (cfg.E0 - cfg.Emin)
            * torch.pow(rho.detach(), cfg.penal - 1.0)
            * Je0
            / J0
        )

        dVabs_drho = elem_areas
        dg_drho = dVabs_drho / V_star_abs
        active_mask = (g_v.detach() > 0.0).to(cfg.dtype)

        dL_drho = dJ_drho + (
            alm_lambda + alm_mu * g_plus.detach()
        ) * active_mask * dg_drho

        rho.backward(dL_drho)
        optimizer.step()

        if (epoch + 1) % cfg.alm_update_every == 0:
            g_scalar = float(g_v.detach().cpu())
            g_plus_scalar = max(g_scalar, 0.0)

            alm_lambda = max(0.0, alm_lambda + alm_mu * g_scalar)

            if prev_g_plus_for_mu is not None and g_plus_scalar > 0.25 * prev_g_plus_for_mu:
                alm_mu = min(cfg.alm_mu_max, alm_mu * cfg.alm_mu_scale)

            prev_g_plus_for_mu = g_plus_scalar

        rho_cpu = rho.detach().cpu().numpy()

        if previous_rho is None:
            rho_change_max = np.inf
        else:
            rho_change_max = float(np.max(np.abs(rho_cpu - previous_rho)))

        previous_rho = rho_cpu.copy()

        history["epoch"].append(epoch)
        history["compliance"].append(float(compliance))
        history["volfrac"].append(float(volfrac_current.detach().cpu()))
        history["loss"].append(float(loss.detach().cpu()))
        history["rho_change_max"].append(rho_change_max)
        history["volfrac_residual"].append(float(volfrac_residual.detach().cpu()))
        history["alm_lambda"].append(float(alm_lambda))
        history["alm_mu"].append(float(alm_mu))
        history["g_plus"].append(float(g_plus.detach().cpu()))

        compliance_rel_improve = compute_windowed_compliance_improvement(
            history["compliance"],
            cfg.compliance_window,
        )
        history["compliance_rel_improve"].append(compliance_rel_improve)

        enough_epochs = epoch >= cfg.min_epochs_before_stop
        volume_ok = abs(float(volfrac_residual.detach().cpu())) < cfg.volfrac_residual_tol
        rho_ok = rho_change_max < cfg.rho_change_max_tol
        compliance_ok = compliance_rel_improve < cfg.compliance_rel_improve_tol

        if enough_epochs and volume_ok or rho_ok and compliance_ok:
            patience_counter += 1
        else:
            patience_counter = 0

        history["patience_counter"].append(patience_counter)

        if epoch % cfg.print_every == 0 or epoch == cfg.max_epochs - 1:
            improve_str = (
                f"{compliance_rel_improve:9.3e}"
                if np.isfinite(compliance_rel_improve)
                else "      inf"
            )

            print(
                f"iter={epoch:5d} | "
                f"J={float(compliance):12.5f} | "
                f"VF={float(volfrac_current.detach().cpu()):7.4f} | "
                f"gVF={float(volfrac_residual.detach().cpu()):+9.5f} | "
                f"max|dRho|={rho_change_max:9.3e} | "
                f"rel dC={improve_str} | "
                f"pat={patience_counter:3d}/{cfg.patience:3d}"
            )

        if patience_counter >= cfg.patience:
            print(f"Converged at iteration {epoch}.")
            break

    return model, history, problem_data, device


