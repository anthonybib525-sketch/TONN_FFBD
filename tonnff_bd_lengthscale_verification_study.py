    solid_min_thickness = np.nan
    void_violation_fraction = np.nan
    void_min_thickness = np.nan

    if solid.get("valid", False):
        solid_violation_fraction = float(solid["violation_fraction"])
        solid_min_thickness = float(solid["min_thickness"])

