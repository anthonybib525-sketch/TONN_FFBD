class BoundedDiskFourierFeatureMap(nn.Module):
    def __init__(
        self,
        in_dim: int,
        num_fourier_features: int,
        fmax: float,
        seed: int = 0,
    ):
        super().__init__()

        if in_dim != 2:
            raise ValueError("This Fourier map assumes 2D coordinates.")
        if fmax <= 0:
            raise ValueError("fmax must be positive.")

        gen = torch.Generator(device="cpu")
        gen.manual_seed(seed)

        theta = 2.0 * math.pi * torch.rand(num_fourier_features, generator=gen)
        r = fmax * torch.rand(num_fourier_features, generator=gen)

        bx = r * torch.cos(theta)
        by = r * torch.sin(theta)

        B = torch.stack([bx, by], dim=1)

        self.fmax = fmax
        self.register_buffer("B", B)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        xb = 2.0 * math.pi * (x @ self.B.T)
        return torch.cat([torch.cos(xb), torch.sin(xb)], dim=1)


